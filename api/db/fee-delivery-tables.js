const { db } = require('./config');

async function ensureFeeDeliveryTables() {
  const client = await db.connect();
  try {
    await client.query('BEGIN');
    await client.query(`
      CREATE TABLE IF NOT EXISTS public.fee_batches (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        bill_date DATE NOT NULL UNIQUE,
        source_hash TEXT NOT NULL,
        account_id INTEGER NOT NULL REFERENCES public.host_bank_accounts(id) ON DELETE RESTRICT,
        account_snapshot JSONB NOT NULL,
        created_by TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `);
    await client.query(`
      CREATE TABLE IF NOT EXISTS public.fee_requests (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        batch_id BIGINT NOT NULL REFERENCES public.fee_batches(id) ON DELETE RESTRICT,
        request_index INTEGER NOT NULL,
        telegram_user_id BIGINT NOT NULL CHECK (telegram_user_id > 0),
        display_name TEXT NOT NULL,
        team TEXT NOT NULL CHECK (team IN ('HOME', 'AWAY')),
        amount INTEGER NOT NULL CHECK (amount > 0),
        transfer_note TEXT NOT NULL UNIQUE,
        delivery_status TEXT NOT NULL DEFAULT 'pending'
          CHECK (delivery_status IN ('pending', 'sending', 'sent', 'failed')),
        telegram_message_id BIGINT,
        delivery_error TEXT,
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        UNIQUE (batch_id, telegram_user_id),
        UNIQUE (batch_id, request_index)
      )
    `);
    await client.query(
      'ALTER TABLE public.fee_batches ENABLE ROW LEVEL SECURITY'
    );
    await client.query(
      'ALTER TABLE public.fee_requests ENABLE ROW LEVEL SECURITY'
    );
    const { rows } = await client.query(
      'SELECT rolname FROM pg_roles WHERE rolname = ANY($1::text[])',
      [['anon', 'authenticated']]
    );
    for (const { rolname } of rows) {
      await client.query(
        `REVOKE ALL PRIVILEGES ON TABLE public.fee_batches, public.fee_requests FROM ${rolname}`
      );
      await client.query(
        `REVOKE ALL PRIVILEGES ON SEQUENCE public.fee_batches_id_seq, public.fee_requests_id_seq FROM ${rolname}`
      );
    }
    await client.query('COMMIT');
  } catch (error) {
    await client.query('ROLLBACK');
    throw error;
  } finally {
    client.release();
  }
}

module.exports = { ensureFeeDeliveryTables };
